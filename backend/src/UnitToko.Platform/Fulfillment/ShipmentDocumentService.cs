using System.Text;
using MongoDB.Bson;
using MongoDB.Driver;
using UnitToko.Modules.Contracts;
using UnitToko.Modules.Identity;
using UnitToko.Modules.Identity.Contracts;
using UnitToko.Modules.Organizations;
using UnitToko.Platform.Authorization;
using UnitToko.Platform.Documents;
using UnitToko.Platform.Mongo;

namespace UnitToko.Platform.Fulfillment;

public sealed record ShipmentDocumentView(LongId Id, LongId ShipmentId, long ShipmentRevision, long Version, string ContentHash, long ByteLength, DateTimeOffset IssuedAt);
public sealed record ShipmentDocumentDownload(ShipmentDocumentView Document, string Content, string FileName);

/// <summary>Fulfillment authorizes issuance/download; Documents owns fixed generated bytes.
/// No public storage URL, live template rendering, financial authority or recipient consent.</summary>
public sealed class ShipmentDocumentService
{
    internal const string Operation = IssuedDocumentStore.Operation;
    private readonly IMongoDatabase database;
    private readonly IdAllocator ids;
    private readonly IClock clock;
    private readonly ShipmentQueryService shipments;
    private readonly AuthorizationStore authorization;
    private readonly IssuedDocumentStore documents;
    public ShipmentDocumentService(IMongoDatabase database, MongoUnitOfWork unit, IdAllocator ids, IClock clock, ShipmentQueryService shipments) {
        if (!ReferenceEquals(database.Client, shipments.SourceDatabase.Client) || !database.DatabaseNamespace.Equals(shipments.SourceDatabase.DatabaseNamespace))
            throw new ArgumentException("Issued documents must share the source owner's database transaction");
        this.database = database; this.ids = ids; this.clock = clock; this.shipments = shipments;
        authorization = new(database, unit, clock); documents = new(database);
    }
    private IMongoCollection<BsonDocument> Rows(string name) => database.GetCollection<BsonDocument>(name);
    private async Task StorageAsync(CancellationToken ct) { await shipments.StorageAsync(ct); await documents.StorageAsync(ct); }
    private static object Body(long id, long revision) => new { shipmentId = id, shipmentRevision = revision };
    private static ShipmentDocumentView View(BsonDocument row) => new(new(row["_id"].AsInt64), new(row["sourceId"].AsInt64), row["sourceRevision"].AsInt64,
        row["version"].AsInt64, row["contentHash"].AsString, row["byteLength"].AsInt64, DateTimeOffset.FromUnixTimeMilliseconds(row["issuedAt"].AsBsonDateTime.MillisecondsSinceEpoch));
    private async Task<BsonDocument> VerifiedAsync(IClientSessionHandle tx, BsonDocument row, ShipmentDocumentSource source, CancellationToken ct) {
        if (row["bodyHash"] != AuthorizationStore.CommandHash(Body(row["sourceId"].AsInt64, row["sourceRevision"].AsInt64), row["reason"].AsString)) throw IssuedDocumentStore.Invalid();
        return await documents.VerifyAsync(tx, row, source.Snapshot, ct);
    }
    public async Task<ShipmentDocumentView> IssueAsync(ActorContext actor, long shipmentId, long revision, AuthorizationCommandMetadata metadata, CancellationToken ct = default) {
        AuthorizationStore.ValidateMetadata(metadata);
        if (shipmentId <= 0 || revision != 1) throw new DomainValidationException("invalid_shipment_document", "Use the accepted shipment version");
        await StorageAsync(ct); var id = (await ids.NextAsync(IssuedDocumentStore.Collection, ct)).Value; var auditId = (await ids.NextAsync("auditEvents", ct)).Value;
        ShipmentDocumentSource source = null!; var body = Body(shipmentId, revision);
        var result = await authorization.ExecuteCommandAsync(actor, Operation, metadata, body, async (snapshot, tx, token) => {
            source = await shipments.DocumentSourceAsync(actor, snapshot, tx, shipmentId, Permissions.ShipmentPrepare, token);
            var existing = await documents.FindAsync(tx, shipmentId, token);
            if (existing is not null) await VerifiedAsync(tx, existing, source, token);
            return new(ScopePolicy.Authorize(actor, snapshot, Permissions.ShipmentPrepare, source.Resource, clock.UtcNow),
                ScopePolicy.RequiredNodes(source.Resource, snapshot.Directory), Permissions.ShipmentPrepare, new(source.Resource));
        }, async (tx, token) => {
            var now = DateTimeOffset.FromUnixTimeMilliseconds(clock.UtcNow.ToUnixTimeMilliseconds());
            if (now.ToUnixTimeMilliseconds() < source.Snapshot["dispatchedAt"].AsBsonDateTime.MillisecondsSinceEpoch) throw IssuedDocumentStore.Invalid();
            var content = SuratJalanRenderer.Render(source.Snapshot, id, now);
            var row = new BsonDocument { { "_id", id }, { "schemaVersion", 1 }, { "kind", IssuedDocumentStore.Kind },
                { "sourceId", shipmentId }, { "sourceRevision", revision }, { "version", 1L }, { "renderer", "surat-jalan-html-v1" },
                { "mediaType", "text/html; charset=utf-8" }, { "snapshot", source.Snapshot }, { "content", content },
                { "contentHash", IssuedDocumentStore.Hash(content) }, { "byteLength", (long)Encoding.UTF8.GetByteCount(content) },
                { "issuedBy", actor.UserId }, { "actorGrantVersion", actor.GrantVersion }, { "issuedAt", now.UtcDateTime },
                { "auditId", auditId }, { "requestKey", metadata.IdempotencyKey }, { "bodyHash", AuthorizationStore.CommandHash(body, metadata.Reason) },
                { "reason", metadata.Reason }, { "correlationId", metadata.CorrelationId } };
            await documents.InsertAsync(tx, row, token);
            await Rows("auditEvents").InsertOneAsync(tx, IssuedDocumentStore.Audit(row), cancellationToken: token);
            await Rows("outboxEvents").InsertOneAsync(tx, new BsonDocument { { "_id", ObjectId.GenerateNewId() }, { "schemaVersion", 1 },
                { "kind", IssuedDocumentStore.Kind + ".issued" }, { "sourceKey", IssuedDocumentStore.Kind + ".issued:" + id },
                { "payload", IssuedDocumentStore.Result(row) }, { "createdAt", now.UtcDateTime }, { "dueAt", now.UtcDateTime }, { "status", "pending" }, { "attempts", 0 } }, cancellationToken: token);
            return IssuedDocumentStore.Result(row);
        }, ct, async (snapshot, tx, token) => {
            var row = await documents.FindAsync(tx, shipmentId, token) ?? throw IssuedDocumentStore.Invalid();
            if (row["issuedBy"] != actor.UserId || row["requestKey"] != metadata.IdempotencyKey || row["bodyHash"] != AuthorizationStore.CommandHash(body, metadata.Reason)) throw IssuedDocumentStore.Invalid();
            await VerifiedAsync(tx, row, source, token);
            await shipments.FenceAsync(actor, snapshot, tx, [source.Resource], token, Permissions.ShipmentPrepare);
        });
        return new(new(result["documentId"].AsInt64), new(result["shipmentId"].AsInt64), result["shipmentRevision"].AsInt64, result["version"].AsInt64,
            result["contentHash"].AsString, result["byteLength"].AsInt64, DateTimeOffset.FromUnixTimeMilliseconds(result["issuedAt"].AsBsonDateTime.MillisecondsSinceEpoch));
    }
    public async Task<ShipmentDocumentView?> ReadAsync(ActorContext actor, long shipmentId, CancellationToken ct = default) {
        await StorageAsync(ct);
        return await authorization.ReadAsync(actor, async (snapshot, tx, token) => {
            var source = await shipments.DocumentSourceAsync(actor, snapshot, tx, shipmentId, Permissions.ShipmentRead, token);
            var row = await documents.FindAsync(tx, shipmentId, token);
            var result = row is null ? null : View(await VerifiedAsync(tx, row, source, token));
            await shipments.FenceAsync(actor, snapshot, tx, [source.Resource], token); return result;
        }, ct);
    }
    public async Task<ShipmentDocumentDownload> DownloadAsync(ActorContext actor, long shipmentId, long documentId, CancellationToken ct = default) {
        await StorageAsync(ct);
        return await authorization.ReadAsync(actor, async (snapshot, tx, token) => {
            var source = await shipments.DocumentSourceAsync(actor, snapshot, tx, shipmentId, Permissions.ShipmentRead, token);
            var row = await documents.FindAsync(tx, shipmentId, token) ?? throw IssuedDocumentStore.Invalid();
            if (row["_id"] != documentId) throw IssuedDocumentStore.Invalid();
            await VerifiedAsync(tx, row, source, token);
            var result = new ShipmentDocumentDownload(View(row), row["content"].AsString, FormattableString.Invariant($"surat-jalan-{shipmentId}-v1-{documentId}.html"));
            await shipments.FenceAsync(actor, snapshot, tx, [source.Resource], token); return result;
        }, ct);
    }
    public async Task<ShipmentDocumentView?> RecoverAsync(ActorContext actor, string key, CancellationToken ct = default) {
        // Lookup only: it can never render, issue or allocate a replacement document.
        AuthorizationStore.ValidateMetadata(new(key, "Recover original Surat Jalan", "surat-jalan-recovery")); await StorageAsync(ct);
        return await authorization.ReadAsync(actor, async (snapshot, tx, token) => {
            AuthorizationStore.Require(ScopePolicy.Compile(actor, snapshot, Permissions.ShipmentPrepare, clock.UtcNow));
            var rows = await Rows(IssuedDocumentStore.Collection).Find(tx, new BsonDocument { { "issuedBy", actor.UserId }, { "requestKey", key } }).Limit(2).ToListAsync(token);
            var receipt = await Rows("idempotencyRecords").Find(tx, new BsonDocument { { "actorId", actor.UserId }, { "operation", Operation }, { "key", key } }).SingleOrDefaultAsync(token);
            if (rows.Count == 0 && receipt is null) {
                await shipments.FenceAsync(actor, snapshot, tx, [], token, Permissions.ShipmentPrepare); return null;
            }
            if (rows.Count != 1 || receipt is null) throw IssuedDocumentStore.Invalid();
            var row = rows[0]; var source = await shipments.DocumentSourceAsync(actor, snapshot, tx, row["sourceId"].AsInt64, Permissions.ShipmentPrepare, token);
            var result = View(await VerifiedAsync(tx, row, source, token));
            await shipments.FenceAsync(actor, snapshot, tx, [source.Resource], token, Permissions.ShipmentPrepare); return result;
        }, ct);
    }
}
